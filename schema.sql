create extension if not exists pgcrypto;

-- 使用者資料與角色。角色預設 worker，主管由管理者手動升級。
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'worker' check (role in ('worker', 'supervisor')),
  created_at timestamptz not null default now()
);

create or replace function public.is_supervisor()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'supervisor'
  );
$$;

revoke all on function public.is_supervisor() from public;
grant execute on function public.is_supervisor() to authenticated;

-- 新增 Auth 使用者時，自動建立 worker profile。
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)),
    'worker'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create table if not exists public.equipment_catalog (
  id bigint generated by default as identity primary key,
  name text not null unique,
  specs text[] not null default '{}',
  unit text not null default '個',
  active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

create table if not exists public.work_entries (
  id uuid primary key default gen_random_uuid(),
  work_date date not null,
  site_name text not null,
  site_address text,
  floor_area text,
  equipment_name text not null,
  equipment_spec text,
  work_type text not null check (work_type in ('移置','新設','更換','維修','拆除','測試')),
  quantity numeric(12,2) not null check (quantity > 0),
  unit text not null,
  status text not null default '已完工' check (status in ('已完工','施工中','待處理')),
  point_name text,
  notes text,
  photo_paths text[] not null default '{}',
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists work_entries_work_date_idx on public.work_entries(work_date desc);
create index if not exists work_entries_site_name_idx on public.work_entries(site_name);
create index if not exists work_entries_created_by_idx on public.work_entries(created_by);
create index if not exists work_entries_equipment_idx on public.work_entries(equipment_name, work_type);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists work_entries_updated_at on public.work_entries;
create trigger work_entries_updated_at
before update on public.work_entries
for each row execute procedure public.set_updated_at();

