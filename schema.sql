-- Profiles：本人可讀自己的資料；主管可讀全員資料。使用者不能自行更改角色。
drop policy if exists "profiles_read_self_or_supervisor" on public.profiles;
create policy "profiles_read_self_or_supervisor"
on public.profiles for select to authenticated
using (id = auth.uid() or public.is_supervisor());

drop policy if exists "profiles_update_self_name_or_supervisor" on public.profiles;
create policy "profiles_update_self_name_or_supervisor"
on public.profiles for update to authenticated
using (id = auth.uid() or public.is_supervisor())
with check (
  public.is_supervisor()
  or (id = auth.uid() and role = 'worker')
);

-- 設備目錄：登入者可讀，僅主管可新增、修改、停用。
drop policy if exists "catalog_read_authenticated" on public.equipment_catalog;
create policy "catalog_read_authenticated"
on public.equipment_catalog for select to authenticated
using (true);

drop policy if exists "catalog_manage_supervisor" on public.equipment_catalog;
create policy "catalog_manage_supervisor"
on public.equipment_catalog for all to authenticated
using (public.is_supervisor())
with check (public.is_supervisor());

-- 施工紀錄：施工人員只能新增自己的紀錄、讀寫自己的紀錄；
-- 主管可以查看及管理全公司紀錄。
drop policy if exists "entries_read_own_or_supervisor" on public.work_entries;
create policy "entries_read_own_or_supervisor"
on public.work_entries for select to authenticated
using (created_by = auth.uid() or public.is_supervisor());

drop policy if exists "entries_insert_own" on public.work_entries;
create policy "entries_insert_own"
on public.work_entries for insert to authenticated
with check (created_by = auth.uid());

drop policy if exists "entries_update_own_or_supervisor" on public.work_entries;
create policy "entries_update_own_or_supervisor"
on public.work_entries for update to authenticated
using (created_by = auth.uid() or public.is_supervisor())
with check (created_by = auth.uid() or public.is_supervisor());

drop policy if exists "entries_delete_own_or_supervisor" on public.work_entries;
create policy "entries_delete_own_or_supervisor"
on public.work_entries for delete to authenticated
using (created_by = auth.uid() or public.is_supervisor());

